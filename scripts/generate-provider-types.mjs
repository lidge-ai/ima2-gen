import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import ts from "typescript";

const ROOT = resolve(import.meta.dirname, "..");
const TARGET = resolve(ROOT, "ui/src/generated/providers.ts");
const VIDEO_TARGET = resolve(ROOT, "ui/src/generated/api88VideoSpecs.ts");

async function loadTsModule(relativePath) {
  try {
    const source = await readFile(resolve(ROOT, relativePath), "utf8");
    const output = ts.transpileModule(source, {
      compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
    }).outputText;
    const moduleUrl = `data:text/javascript;base64,${Buffer.from(output).toString("base64")}`;
    return await import(moduleUrl);
  } catch (error) {
    throw new Error(`Could not load provider source ${relativePath}`, { cause: error });
  }
}

function literal(value) {
  return JSON.stringify(value, null, 2);
}

function surfaceLiteral(value) {
  const rows = Object.entries(value).map(([id, surfaces]) => {
    const fields = Object.entries(surfaces)
      .map(([surface, facts]) => `    ${JSON.stringify(surface)}: ${JSON.stringify(facts)}`);
    return `  ${JSON.stringify(id)}: {\n${fields.join(",\n")}\n  }`;
  });
  return `{\n${rows.join(",\n")}\n}`;
}

function videoOutput(specs) {
  const rows = Object.entries(specs).map(([id, spec]) => {
    const value = { durations: spec.durations, defaultDuration: spec.defaultDuration,
      ratios: spec.ratios, resolutions: spec.resolutions, imageLimit: spec.refs.images,
      veoBase64: spec.veoBase64,
      imageMode: spec.family === "grok" ? "source" : spec.firstFrame ? "both" : "reference" };
    return `  ${JSON.stringify(id)}: ${JSON.stringify(value)}`;
  });
  return `// Generated by scripts/generate-provider-types.mjs. Do not edit.\n\nexport const API88_VIDEO_SPECS = {\n${rows.join(",\n")}\n} as const;\nexport type Api88VideoModel = keyof typeof API88_VIDEO_SPECS;\n`;
}

function buildOutput(registry, surfaceModule) {
  const providers = registry.map((provider) => provider.id);
  const models = registry.flatMap((provider) => provider.models.map((model) => ({
    ...model,
    provider: provider.id,
  })));
  const unique = (values) => [...new Set(values)];
  const imageModels = unique(models.filter((model) => model.kind === "image").map((model) => model.id));
  const videoModels = unique(models.filter((model) => model.kind === "video").flatMap((model) => [model.id, ...(model.aliases || [])]));
  const supportedImages = unique(models.filter((model) => model.kind === "image" && model.supports.generate).map((model) => model.id));
  const unsupportedImages = imageModels.filter((id) => !supportedImages.includes(id));
  const referenceLimits = Object.fromEntries(registry.map((provider) => [provider.id, provider.referenceLimits]));
  const surfaceSupport = Object.fromEntries(registry.map((provider) => [
    provider.id,
    Object.fromEntries(surfaceModule.PROVIDER_SURFACES.map((surface) => [
      surface, surfaceModule.deriveProviderSurfaceSupportFrom(registry, provider.id, surface),
    ])),
  ]));
  const byProvider = Object.fromEntries(registry.map((provider) => [provider.id, {
    image: provider.models.filter((model) => model.kind === "image").map((model) => model.id),
    video: provider.models.filter((model) => model.kind === "video").flatMap((model) => [model.id, ...(model.aliases || [])]),
  }]));
  return `// Generated by scripts/generate-provider-types.mjs. Do not edit.\n\nimport type { ProviderSurface, ProviderSurfaceSupport } from "../../../lib/providers/types";\nexport type { ProviderSurface, ProviderSurfaceSupport } from "../../../lib/providers/types";\n\nexport const CORE_PROVIDER_IDS = ${literal(providers)} as const;\nexport type CoreProviderId = typeof CORE_PROVIDER_IDS[number];\nexport const CORE_PROVIDER_ID_SET: ReadonlySet<string> = new Set(CORE_PROVIDER_IDS);\nexport function isCoreProviderId(value: unknown): value is CoreProviderId {\n  return typeof value === "string" && CORE_PROVIDER_ID_SET.has(value);\n}\n\nexport const PROVIDER_MODELS = ${literal(byProvider)} as const;\nexport const IMAGE_MODEL_IDS = ${literal(supportedImages)} as const;\nexport type ImageModelId = typeof IMAGE_MODEL_IDS[number];\nexport const UNSUPPORTED_IMAGE_MODEL_IDS = ${literal(unsupportedImages)} as const;\nexport type UnsupportedImageModelId = typeof UNSUPPORTED_IMAGE_MODEL_IDS[number];\nexport const VIDEO_MODEL_IDS = ${literal(videoModels)} as const;\nexport type VideoModelId = typeof VIDEO_MODEL_IDS[number];\nexport const PROVIDER_REFERENCE_LIMITS = ${literal(referenceLimits)} as const;\n\nexport const PROVIDER_SURFACE_SUPPORT = ${surfaceLiteral(surfaceSupport)} as const satisfies Record<CoreProviderId, Record<ProviderSurface, ProviderSurfaceSupport>>;\n`;
}

async function main() {
  const [registryModule, surfaceModule, videoModule] = await Promise.all([
    loadTsModule("lib/providers/registry.ts"),
    loadTsModule("lib/providers/surfaceSupport.ts"),
    loadTsModule("lib/api88/videoSpecs.ts"),
  ]);
  const outputs = [[TARGET, buildOutput(registryModule.REGISTRY, surfaceModule)],
    [VIDEO_TARGET, videoOutput(videoModule.API88_VIDEO_SPECS)]];
  for (const [target, expected] of outputs) {
    if (process.argv.includes("--check")) {
      const current = await readFile(target, "utf8").catch(() => "");
      if (current !== expected) {
        console.error(`${target} is stale; run node scripts/generate-provider-types.mjs`);
        process.exitCode = 1;
      }
    } else {
      await writeFile(target, expected);
    }
  }
}

try {
  await main();
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
